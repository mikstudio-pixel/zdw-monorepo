"""Reconstruct the tutorial path on a copy, never mutate the supplied projects.
Control points and palette are fitted to two final tutorial frames. The same
definition generates the AE copy and shared WebGL data. This is a reconstruction,
not the author's original control points or palette.
"""
from pathlib import Path
import re
import json
import struct

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / 'reference/tutorial'
xml = (REF / 'liquid-delivery.aepx').read_text()
# Composition display in the recording: origin (650,227), scale 0.375.
# Cubic path: vertex, out, in, vertex, out, in, vertex, out, in.
points = [(872,526),(927,472),(996,485),(1072,490),(1090,500),(931,419),(978,337),(978,337),(872,526)]
points = [((x-1010)/.375,(y-429.5)/.375) for x,y in points]
if (REF/'fitted-filtered-path.json').exists():
    points=json.loads((REF/'fitted-filtered-path.json').read_text())['points']
    points=points+[points[-1],points[0]]
lo = [min(p[i] for p in points) for i in (0,1)]
hi = [max(p[i] for p in points) for i in (0,1)]
shapes = list(re.finditer(r'<shap>.*?</shap>',xml,re.S))
assert len(shapes)==2
shape=shapes[1].group()
shape=re.sub(r'(<shph bdata=")[0-9a-f]+',lambda m:m[1]+(bytes.fromhex('b3de0209')+struct.pack('>4f',*lo,*hi)+bytes.fromhex('01000000')).hex(),shape)
coords=[(p[i]-lo[i])/(hi[i]-lo[i]) for p in points for i in (0,1)]
shape=re.sub(r'(<ldat bdata=")[0-9a-f]+',lambda m:m[1]+struct.pack('>18f',*coords).hex(),shape)
xml=xml[:shapes[1].start()]+shape+xml[shapes[1].end():]
palette=json.loads((REF/'fitted-palette.json').read_text())
data=bytearray(520)
for i,(position,color) in enumerate(zip(palette['positions'],palette['colors'])):
    data[i*8:i*8+8]=struct.pack('>I4B',round(position*65535),255,*color)
data[512:516]=struct.pack('>I',len(palette['positions']))
xml,count=re.subn(r'<aRbp bdata="[0-9a-f]+"/>','<aRbp bdata="'+data.hex()+'"/>',xml)
assert count==4
(REF/'liquid-calibrated.aepx').write_text(xml)
definition={
    'start':[[-744,30],[-534,-80],[-386,-108],[-166,-68],[104,-13],[440,110],[710,-120]],
    'end':points[:7],
    'positions':palette['positions'],
    'colors':palette['colors'],
}
(ROOT/'src/liquid-definition.js').write_text('// Generated by scripts/calibrate-liquid-reference.py; reconstructed tutorial data.\nexport const LIQUID_REFERENCE = '+json.dumps(definition,indent=2)+';\n')
print(REF/'liquid-calibrated.aepx')
