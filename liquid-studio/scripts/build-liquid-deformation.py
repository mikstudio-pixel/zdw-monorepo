"""Pack measured AE coordinate fields, not rendered liquid images, for WebGL."""
import base64,gzip,hashlib,json,subprocess
from pathlib import Path
import numpy as np
ROOT=Path(__file__).resolve().parent.parent
REF=ROOT/'reference/tutorial'
W,H,N=480,270,45
maps=[]
valid=[]
for axis in ('x','y'):
 files=sorted((REF/f'turbulence-{axis}').glob('*.png'))
 assert len(files)==N,(axis,len(files))
 data=subprocess.check_output(['ffmpeg','-v','error','-pattern_type','glob','-i',str(REF/f'turbulence-{axis}/*.png'),'-vf',f'scale={W}:{H}:flags=bilinear','-pix_fmt','rgba64le','-f','rawvideo','-'])
 image=np.frombuffer(data,dtype='<u2').reshape(N,H,W,4)
 valid.append(image[...,3].astype(np.float32)/65535)
 a=image[...,0].astype(np.float32)/65535
 extent=1600 if axis=='x' else 1000
 maps.append(extent-a*extent*2)
coords=np.stack(maps,axis=-1)
y,x=np.mgrid[:H,:W]
grid=np.stack([(x+.5)*1920/W-960,(y+.5)*1080/H-540],axis=-1)
# Delta avoids losing subpixel precision to a large absolute position.
np.save(REF/'turbulence-coordinates.npy',coords)
coords=coords.reshape(N,135,2,240,2,2).mean(axis=(2,4))
y,x=np.mgrid[:135,:240]
grid=np.stack([(x+.5)*8-960,(y+.5)*8-540],axis=-1)
quantized=np.rint((coords-grid)*4).astype('<i2')
delta=quantized.copy()
delta[1:]-=delta[:-1].copy()
delta[:,:,1:]-=delta[:,:,:-1].copy()
packed=gzip.compress(delta.tobytes(),compresslevel=9,mtime=0)
encoded=base64.b64encode(packed).decode()
validity=np.minimum(*valid).reshape(N,135,2,240,2).min(axis=(2,4))
validEncoded=base64.b64encode(gzip.compress(np.rint(validity*255).astype('u1').tobytes(),mtime=0)).decode()
module='''// Generated by scripts/build-liquid-deformation.py from native AE probes.
// Quarter-pixel inverse displacement, 240x135x45, sampled every 0.1 s.
// Contains coordinates only; path, palette, compositing and interaction stay live.
const compressedDeformation = Uint8Array.from(atob('''+repr(encoded)+'''), c => c.charCodeAt(0));
const deformationStream = new Blob([compressedDeformation]).stream().pipeThrough(new DecompressionStream('gzip'));
const deformationDeltas = new Int16Array(await new Response(deformationStream).arrayBuffer());
const validityStream = new Blob([Uint8Array.from(atob('''+repr(validEncoded)+'''), c => c.charCodeAt(0))]).stream().pipeThrough(new DecompressionStream('gzip'));
const deformationValidity = new Uint8Array(await new Response(validityStream).arrayBuffer());
const deformationPixels = new Float32Array(deformationDeltas.length*2);
for (let z=0;z<45;z++) for (let y=0;y<135;y++) for (let x=0;x<240;x++) for (let c=0;c<2;c++) {
  const i=((z*135+y)*240+x)*2+c;
  if(x) deformationDeltas[i]+=deformationDeltas[i-2];
}
for(let i=0;i<deformationDeltas.length;i++) {
  if(i>=240*135*2) deformationDeltas[i]+=deformationDeltas[i-240*135*2];
  deformationPixels[Math.floor(i/2)*4+i%2]=deformationDeltas[i]/4320;
}
for(let i=0;i<deformationValidity.length;i++) deformationPixels[i*4+3]=deformationValidity[i]/255;
export function createDeformationTexture(gl) {
  const texture = gl.createTexture();
  gl.activeTexture(gl.TEXTURE4); gl.bindTexture(gl.TEXTURE_3D, texture);
  gl.texParameteri(gl.TEXTURE_3D, gl.TEXTURE_MIN_FILTER, gl.LINEAR);
  gl.texParameteri(gl.TEXTURE_3D, gl.TEXTURE_MAG_FILTER, gl.LINEAR);
  for (const key of [gl.TEXTURE_WRAP_S, gl.TEXTURE_WRAP_T, gl.TEXTURE_WRAP_R]) gl.texParameteri(gl.TEXTURE_3D, key, gl.CLAMP_TO_EDGE);
  gl.texImage3D(gl.TEXTURE_3D, 0, gl.RGBA16F, 240, 135, 45, 0, gl.RGBA, gl.FLOAT, deformationPixels);
  gl.activeTexture(gl.TEXTURE0);
  return texture;
}
export function bindDeformation(gl, texture, uniforms) {
  if (uniforms.u_deformation === undefined) return;
  gl.activeTexture(gl.TEXTURE4); gl.bindTexture(gl.TEXTURE_3D, texture);
  gl.uniform1i(uniforms.u_deformation, 4);
  gl.activeTexture(gl.TEXTURE0);
}
'''
(ROOT/'src/liquid-deformation.js').write_text(module)
(REF/'deformation-manifest.json').write_text(json.dumps({
 'size':[240,135,N], 'stepSeconds':.1, 'settledAtSeconds':4.36,
 'format':'Spatial + temporal Int16 deltas, quarter-pixel quantization; decoded to RGBA16F normalized by 1080',
 'gzipBytes':len(packed), 'sha256':hashlib.sha256(delta.tobytes()).hexdigest(),
 'source':'Native Turbulent Displace applied to orthogonal linear gradients; full-resolution 16bpc PNG probes.',
 'sourceProjects':{f.name:hashlib.sha256(f.read_bytes()).hexdigest() for f in [REF/'turbulence-0.aepx',REF/'turbulence-1.aepx']},
},indent=2))
print('Map gzip bytes:',len(packed),'module bytes:',len(module))
