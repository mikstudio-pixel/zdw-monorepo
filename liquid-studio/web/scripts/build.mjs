import { build } from 'esbuild';
import { mkdir, readFile, writeFile, copyFile, cp } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
await mkdir(`${root}dist`, { recursive: true });
await mkdir(`${root}dist/assets`, { recursive: true });
for (const file of ['zdw-demo.mp4', 'zdw-demo-portrait.mp4']) await copyFile(`${root}assets/${file}`, `${root}dist/assets/${file}`);
await cp(`${root}assets/icons`, `${root}dist/assets/icons`, { recursive: true });
await copyFile(`${root}src/startup.js`, `${root}dist/startup.js`);
await build({ entryPoints: [`${root}src/bootstrap.js`], outfile: `${root}dist/app.js`, bundle: true, format: 'esm', target: 'safari18', sourcemap: true });
let html = await readFile(`${root}../desktop/renderer/index.html`, 'utf8');
html = html.replace('<body>', '<body class="guided">\n  <script src="./startup.js"></script>');
html = html.replace('width=device-width,initial-scale=1', 'width=device-width,initial-scale=1,viewport-fit=cover');
html = html.replace("media-src 'self'", "media-src 'self' blob:");
html = html.replace("img-src 'self' data:", "img-src 'self' data: blob:");
html = html.replace("connect-src 'self'", "connect-src 'self' blob:; worker-src 'self' blob:");
await writeFile(`${root}dist/index.html`, html);
await writeFile(`${root}dist/style.css`, await readFile(`${root}../desktop/renderer/style.css`, 'utf8') + '\n' + await readFile(`${root}src/flow.css`, 'utf8'));
console.log('Web app built in web/dist (shared desktop renderer).');
